FieldType = Literal["text", "choice", "decimal", "integer", "datetime", "date", "bool"]
FilledBy = Literal["ai", "link", "system_id", "reviewer", "later", "derived"]


class FieldSpec(BaseModel):
    name: str
    group: str
    level: Level
    type: FieldType = "text"
    essential: bool = False
    missing: Literal["Missing", "N/A", ""] = ""   # what the export writes when empty ("" = leave blank)
    filled_by: FilledBy = "ai"
    description: str
    choices: list[str] | None = None
    suggested: list[str] | None = None  # Text field with a preferred list: outside it -> warning only
    verbatim: bool = False
    needs_quote: bool = True
    exported: bool = True          # appears as a main export column (template + paper-level)
    electrical_only: bool = False  # essential/Missing only apply to electrical rows

    @property
    def label(self) -> str:
        return self.name

    @property
    def ai_filled(self) -> bool:
        return self.filled_by in ("ai", "link")


def _f(name, group, level, type_, essential, missing, filled_by, description, **kw) -> FieldSpec:
    if type_ == "choice" and "choices" not in kw:
        kw["choices"] = TEMP_CHOICES[name]
    if name in TEMP_SUGGESTED:
        kw.setdefault("suggested", TEMP_SUGGESTED[name])
    return FieldSpec(
        name=name, group=group, level=level, type=type_, essential=essential, missing=missing,
        filled_by=filled_by, description=description,
        verbatim=name in VERBATIM, needs_quote=filled_by == "ai" and name not in NO_QUOTE,
        electrical_only=group == "Electrical setup", **kw)


