def ai_fields(level: str) -> list[FieldSpec]:
    """Fields the AI fills (and the reviewer may edit) for records of this level."""
    return [f for f in FIELDS if f.level == level and f.ai_filled]


def _choice_key(s: str) -> str:
    return re.sub(r"[\s_\-]+", "_", normalize(s)).strip("_")


def choice_ok(spec: FieldSpec, value: str) -> bool:
    allowed = (spec.choices or []) + list(ALWAYS_ALLOWED)
    return _choice_key(value) in {_choice_key(c) for c in allowed}


def suggested_ok(spec: FieldSpec, value: str) -> bool:
    if not spec.suggested:
        return True
    return _choice_key(value) in {_choice_key(c) for c in spec.suggested + list(ALWAYS_ALLOWED)}


def is_electrical(trait_group: str | None, metric_code: str | None) -> bool:
    return (_choice_key(trait_group or "") in {_choice_key(x) for x in ELECTRICAL_TRAIT_GROUPS}
            or _choice_key(metric_code or "") in {_choice_key(x) for x in ELECTRICAL_METRIC_CODES})


class FieldValue(BaseModel):
    value: str | None = None
    quote: str | None = None


class RecordContent(BaseModel):
    fields: dict[str, FieldValue]
    # Required fields the AI looked for but the paper does not give (prompt v7). An empty required
    # field listed here is a warning ("the paper does not say"); one not listed stays an error.
    not_stated: list[str] = []
    # v11: fields copied from a condition template -> template name (a missing quote there is one
    # problem, reported once per document, not once per condition). Dropped when a reviewer edits it.
    from_template: dict[str, str] = {}

    @classmethod
    def empty(cls, level: str) -> "RecordContent":
        return cls(fields={f.name: FieldValue() for f in ai_fields(level)})

    def get(self, name: str) -> str | None:
        fv = self.fields.get(name)
        v = (fv.value or "").strip() if fv else ""
        return v or None
